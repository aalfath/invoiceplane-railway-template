#!/bin/bash
# Railway start script for InvoicePlane: prepares the /data volume, writes ipconfig.php from the
# Railway variables, installs or migrates the database (under a lock), creates the first admin,
# then runs Apache in the foreground. An unexpected stop exits non-zero so Railway restarts it.
set -euo pipefail

log() { echo "=> [railway] $*"; }
fail() { log "ERROR: $*"; exit 1; }

export PORT="${PORT:-80}"
export APACHE_MAX_WORKERS="${APACHE_MAX_WORKERS:-8}"
export TZ="${TZ:-UTC}"
export DB_PORT="${DB_PORT:-3306}"

# The public URL: IP_URL, else the Railway domain.
if [ -z "${IP_URL:-}" ] && [ -n "${RAILWAY_PUBLIC_DOMAIN:-}" ]; then
    IP_URL="https://${RAILWAY_PUBLIC_DOMAIN}"
fi
export IP_URL="${IP_URL%/}"

for v in IP_URL DB_HOSTNAME DB_USERNAME DB_PASSWORD DB_DATABASE ENCRYPTION_KEY; do
    [ -n "${!v:-}" ] || fail "$v is not set (see the template's variables)"
done
if [ "${#ENCRYPTION_KEY}" -lt 32 ]; then
    fail "ENCRYPTION_KEY must be at least 32 characters"
fi

# Values go into ipconfig.php line by line: refuse newlines so nothing can inject a setting.
safe() {
    case "$1" in *$'\n'* | *$'\r'*) fail "a configuration value contains a newline" ;; esac
    printf '%s' "$1"
}

# 1. Persistent state on the Railway volume at /data:
#    /data/uploads (logos, client files, archived PDFs), /data/storage (sessions, cache, logs)
#    and /data/templates (optional custom invoice/quote templates).
mkdir -p /data/uploads /data/storage /data/templates
cp -an /opt/invoiceplane/uploads/. /data/uploads/
cp -an /opt/invoiceplane/storage/. /data/storage/
mkdir -p /data/storage/framework/sessions /data/storage/temp
[ -f /data/templates/.htaccess ] || echo "Deny from all" > /data/templates/.htaccess
chown -R www-data:www-data /data/uploads /data/storage /data/templates

# 2. ipconfig.php (InvoicePlane's config file), regenerated on every start from the variables.
#    Same keys as upstream's resources/docker/entrypoint.sh, plus the Railway proxy settings.
CONFIG=/var/www/html/ipconfig.php
umask 027
cat > "$CONFIG" <<CFG
# <?php exit('No direct script access allowed'); ?>
# InvoicePlane configuration, generated by railway-start.sh on every start. Edit the Railway variables instead.
IP_URL=$(safe "$IP_URL")
ENABLE_DEBUG=$(safe "${ENABLE_DEBUG:-false}")
CI_ENV=$(safe "${CI_ENV:-production}")
X_FRAME_OPTIONS=$(safe "${X_FRAME_OPTIONS:-SAMEORIGIN}")
ENABLE_X_CONTENT_TYPE_OPTIONS=$(safe "${ENABLE_X_CONTENT_TYPE_OPTIONS:-true}")
SESS_REGENERATE_DESTROY=$(safe "${SESS_REGENERATE_DESTROY:-true}")
DEFAULT_LANGUAGE=$(safe "${DEFAULT_LANGUAGE:-english}")
DISABLE_SETUP=true
REMOVE_INDEXPHP=true
DB_HOSTNAME=$(safe "$DB_HOSTNAME")
DB_USERNAME=$(safe "$DB_USERNAME")
DB_PASSWORD=$(safe "$DB_PASSWORD")
DB_DATABASE=$(safe "$DB_DATABASE")
DB_PORT=$(safe "$DB_PORT")
CUSTOM_TEMPLATES_FOLDER=/data/templates/
CUSTOM_INVOICE_TEMPLATES_PDF=$(safe "${CUSTOM_INVOICE_TEMPLATES_PDF:-}")
CUSTOM_INVOICE_TEMPLATES_PUBLIC=$(safe "${CUSTOM_INVOICE_TEMPLATES_PUBLIC:-}")
CUSTOM_QUOTE_TEMPLATES_PDF=$(safe "${CUSTOM_QUOTE_TEMPLATES_PDF:-}")
CUSTOM_QUOTE_TEMPLATES_PUBLIC=$(safe "${CUSTOM_QUOTE_TEMPLATES_PUBLIC:-}")
SESS_SAVE_PATH=/data/storage/framework/sessions
SESS_EXPIRATION=$(safe "${SESS_EXPIRATION:-864000}")
SESS_MATCH_IP=$(safe "${SESS_MATCH_IP:-false}")
COOKIE_SECURE=$(safe "${COOKIE_SECURE:-true}")
PROXY_IPS=$(safe "${PROXY_IPS:-}")
LEGACY_CALCULATION=$(safe "${LEGACY_CALCULATION:-false}")
ENABLE_INVOICE_DELETION=$(safe "${ENABLE_INVOICE_DELETION:-false}")
DISABLE_READ_ONLY=$(safe "${DISABLE_READ_ONLY:-false}")
PASSWORD_RESET_IP_MAX_ATTEMPTS=$(safe "${PASSWORD_RESET_IP_MAX_ATTEMPTS:-5}")
PASSWORD_RESET_IP_WINDOW_MINUTES=$(safe "${PASSWORD_RESET_IP_WINDOW_MINUTES:-60}")
PASSWORD_RESET_EMAIL_MAX_ATTEMPTS=$(safe "${PASSWORD_RESET_EMAIL_MAX_ATTEMPTS:-3}")
PASSWORD_RESET_EMAIL_WINDOW_HOURS=$(safe "${PASSWORD_RESET_EMAIL_WINDOW_HOURS:-1}")
SUMEX_SETTINGS=$(safe "${SUMEX_SETTINGS:-false}")
SUMEX_URL=$(safe "${SUMEX_URL:-}")
ENCRYPTION_KEY=$(safe "$ENCRYPTION_KEY")
ENCRYPTION_CIPHER=$(safe "${ENCRYPTION_CIPHER:-AES-256}")
SETUP_COMPLETED=true
CFG
umask 022
chown root:www-data "$CONFIG"
chmod 0640 "$CONFIG"

# 3. Database: wait for MariaDB, then install or migrate and create the first admin, under a lock.
php /usr/local/bin/railway-db.php || fail "database setup failed"

# 4. Apache on Railway's PORT, in the foreground.
sed -ri "s/^Listen [0-9]+$/Listen ${PORT}/" /etc/apache2/ports.conf
sed -ri "s/<VirtualHost \*:[0-9]+>/<VirtualHost *:${PORT}>/" /etc/apache2/sites-available/000-default.conf
rm -f /var/run/apache2/apache2.pid
apache2-foreground &
APACHE_PID=$!
stopping=0
trap 'stopping=1; log "stopping"; kill -WINCH "$APACHE_PID" 2>/dev/null || true' TERM INT
log "InvoicePlane is starting on port $PORT ($IP_URL)"
set +e
wait "$APACHE_PID"; rc=$?
while [ "$stopping" = 1 ] && kill -0 "$APACHE_PID" 2>/dev/null; do wait "$APACHE_PID"; rc=$?; done
set -e
if [ "$stopping" = 1 ]; then
    exit 0
fi
log "ERROR: Apache stopped unexpectedly (exit $rc)"
exit $(( rc == 0 ? 1 : rc ))
